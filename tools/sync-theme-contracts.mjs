#!/usr/bin/env node

import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const THIS_FILE = fileURLToPath(import.meta.url)
const TOOLS_DIR = path.dirname(THIS_FILE)
const PROJECT_ROOT = path.resolve(TOOLS_DIR, '..')
const THEMES_ROOT = path.join(PROJECT_ROOT, 'app', 'themes')
const GENERATED_ROOT = path.join(THEMES_ROOT, 'generated')
const MANIFEST_PATH = path.join(PROJECT_ROOT, 'theme', 'theme-manifest.json')

const RESERVED_THEME_DIRS = new Set(['generated'])
const META_FILENAME = 'theme.json'
const REQUIRED_FILES = ['shell.tsx', 'pages.ts', 'sections/index.tsx', 'recipes/index.ts', 'tokens.ts']

function toIdentifier(themeId, suffix) {
  const base = String(themeId)
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => (chr ? chr.toUpperCase() : ''))
    .replace(/[^a-zA-Z0-9]/g, '')

  const safe = base ? `${base[0].toLowerCase()}${base.slice(1)}` : 'theme'
  return `${safe}${suffix}`
}

async function pathExists(targetPath) {
  try {
    await fs.access(targetPath)
    return true
  } catch {
    return false
  }
}

async function readThemeMeta(themeDir) {
  const metaPath = path.join(themeDir, META_FILENAME)
  const raw = await fs.readFile(metaPath, 'utf8')
  return JSON.parse(raw)
}

function normalizeThemeMeta(rawMeta, folderName) {
  const folderId = String(folderName || '').trim().toLowerCase()
  const id = String(rawMeta?.id || folderId).trim().toLowerCase()

  if (!id) {
    throw new Error(`Theme folder "${folderName}" has an empty id in ${META_FILENAME}.`)
  }

  if (id !== folderId) {
    throw new Error(
      `Theme folder "${folderName}" must match theme id "${id}" in ${META_FILENAME}.`
    )
  }

  return {
    id,
    name: String(rawMeta?.name || id),
    description: String(rawMeta?.description || ''),
    status: String(rawMeta?.status || 'stable'),
    isDefault: Boolean(rawMeta?.isDefault),
    // Operator toggle (set via /templates admin page). Hidden from the
    // /create picker but kept in the catalog so existing brands still render.
    disabled: Boolean(rawMeta?.disabled),
  }
}

async function discoverThemes() {
  const dirEntries = await fs.readdir(THEMES_ROOT, { withFileTypes: true })
  const themes = []

  for (const entry of dirEntries) {
    if (!entry.isDirectory()) {
      continue
    }

    if (RESERVED_THEME_DIRS.has(entry.name) || entry.name.startsWith('.')) {
      continue
    }

    const themeDir = path.join(THEMES_ROOT, entry.name)
    const metaPath = path.join(themeDir, META_FILENAME)
    const hasMeta = await pathExists(metaPath)

    if (!hasMeta) {
      continue
    }

    const missing = []
    for (const relativeFile of REQUIRED_FILES) {
      const target = path.join(themeDir, relativeFile)
      if (!(await pathExists(target))) {
        missing.push(relativeFile)
      }
    }

    if (missing.length > 0) {
      throw new Error(
        `Theme "${entry.name}" is missing required contract files: ${missing.join(', ')}`
      )
    }

    const rawMeta = await readThemeMeta(themeDir)
    const meta = normalizeThemeMeta(rawMeta, entry.name)
    themes.push(meta)
  }

  themes.sort((a, b) => a.id.localeCompare(b.id))

  const seenIds = new Set()
  for (const theme of themes) {
    if (seenIds.has(theme.id)) {
      throw new Error(`Duplicate theme id detected: ${theme.id}`)
    }
    seenIds.add(theme.id)
  }

  if (themes.length === 0) {
    throw new Error(`No theme contracts detected in ${THEMES_ROOT}.`) 
  }

  const explicitDefaults = themes.filter((theme) => theme.isDefault)
  if (explicitDefaults.length > 1) {
    throw new Error(
      `Only one theme may set isDefault=true. Found: ${explicitDefaults
        .map((theme) => theme.id)
        .join(', ')}`
    )
  }

  const defaultThemeId = explicitDefaults[0]?.id ||
    (themes.some((theme) => theme.id === 'classic-dealer') ? 'classic-dealer' : themes[0].id)

  return { themes, defaultThemeId }
}

function buildAutoGeneratedBanner() {
  return [
    '/* eslint-disable */',
    '// AUTO-GENERATED FILE. DO NOT EDIT.',
    '// Run: npm run theme:sync',
    '',
  ].join('\n')
}

function buildShellRegistryFile(themes) {
  const banner = buildAutoGeneratedBanner()

  // Each shell is a `next/dynamic` boundary so webpack code-splits it into its
  // own chunk. Only the active theme's shell chunk is fetched at runtime instead
  // of bundling all 14 shells (Header/Footer/Lenis/framer-motion + their CSS) on
  // every page. Default ssr:true keeps the header/footer server-rendered (no LCP
  // flash). Consumed by the client `ThemeShell`.
  const mappings = themes
    .map((theme) => {
      return `  '${theme.id}': dynamic(() => import('../${theme.id}/shell').then((m) => m.themeShell)) as unknown as ThemeShellComponent,`
    })
    .join('\n')

  return `${banner}import dynamic from 'next/dynamic'\nimport type { ThemeShellComponent, ThemeShellRegistry } from '../types'\n\nexport const THEME_SHELL_REGISTRY: ThemeShellRegistry = {\n${mappings}\n}\n`
}

function buildPageRegistryFile(themes) {
  const banner = buildAutoGeneratedBanner()

  // Each theme's pages module is a lazy `import()` loader instead of a static
  // import, so webpack code-splits every theme's page components (Hero,
  // VehicleCard, UsedCarsClient, ...) + their per-page CSS into its own chunk.
  // Only the active theme's pages are loaded, awaited server-side in
  // `getThemePageForBrand`. Previously all 14 themes' page code shipped on
  // every route.
  const mappings = themes
    .map((theme) => {
      return `  '${theme.id}': () => import('../${theme.id}/pages'),`
    })
    .join('\n')

  return `${banner}import type { ThemePageRegistry } from '../types'\n\ntype ThemePageModule = { themePages: ThemePageRegistry }\n\nexport const THEME_PAGE_LOADERS: Record<string, () => Promise<ThemePageModule>> = {\n${mappings}\n}\n`
}

function buildContractRegistryFile(themes) {
  const banner = buildAutoGeneratedBanner()

  const metaImports = themes
    .map((theme) => {
      const importName = toIdentifier(theme.id, 'Meta')
      return `import ${importName} from '../${theme.id}/theme.json'`
    })
    .join('\n')

  const sectionImports = themes
    .map((theme) => {
      const importName = toIdentifier(theme.id, 'Sections')
      return `import { themeSections as ${importName} } from '../${theme.id}/sections'`
    })
    .join('\n')

  const recipeImports = themes
    .map((theme) => {
      const importName = toIdentifier(theme.id, 'Recipes')
      return `import { themeRecipes as ${importName} } from '../${theme.id}/recipes'`
    })
    .join('\n')

  const tokenImports = themes
    .map((theme) => {
      const importName = toIdentifier(theme.id, 'Tokens')
      return `import { themeTokens as ${importName} } from '../${theme.id}/tokens'`
    })
    .join('\n')

  const mappings = themes
    .map((theme) => {
      const metaImport = toIdentifier(theme.id, 'Meta')
      const sectionsImport = toIdentifier(theme.id, 'Sections')
      const recipesImport = toIdentifier(theme.id, 'Recipes')
      const tokensImport = toIdentifier(theme.id, 'Tokens')

      return [
        `  '${theme.id}': {`,
        `    meta: ${metaImport},`,
        `    sections: ${sectionsImport},`,
        `    recipes: ${recipesImport},`,
        `    tokens: ${tokensImport},`,
        '  },',
      ].join('\n')
    })
    .join('\n')

  return `${banner}import type { ThemeCustomizationContractRegistry } from '../types'\n${metaImports}\n${sectionImports}\n${recipeImports}\n${tokenImports}\n\nexport const THEME_CUSTOMIZATION_CONTRACTS: ThemeCustomizationContractRegistry = {\n${mappings}\n}\n`
}

function buildContextRegistryFile(themes) {
  const banner = buildAutoGeneratedBanner()

  const wrapperImports = themes.map((theme) => {
    const id = toIdentifier(theme.id, '')
    return `import { BrandClientWrapper as ${id}BrandClientWrapper } from '../${theme.id}/context/BrandClientWrapper'`
  }).join('\n')

  const stylesImports = themes.map((theme) => {
    const id = toIdentifier(theme.id, '')
    return `import { BrandStyles as ${id}BrandStyles } from '../${theme.id}/context/BrandStyles'`
  }).join('\n')

  const authImports = themes.map((theme) => {
    const id = toIdentifier(theme.id, '')
    return `import { AuthProvider as ${id}AuthProvider } from '../${theme.id}/context/AuthContext'`
  }).join('\n')

  const faviconImports = themes.map((theme) => {
    const id = toIdentifier(theme.id, '')
    return `import { DynamicFavicon as ${id}DynamicFavicon } from '../${theme.id}/context/DynamicFavicon'`
  }).join('\n')

  const mappings = themes.map((theme) => {
    const id = toIdentifier(theme.id, '')
    return [
      `  '${theme.id}': {`,
      `    BrandClientWrapper: ${id}BrandClientWrapper,`,
      `    BrandStyles: ${id}BrandStyles,`,
      `    AuthProvider: ${id}AuthProvider,`,
      `    DynamicFavicon: ${id}DynamicFavicon,`,
      `  },`,
    ].join('\n')
  }).join('\n')

  return `${banner}import type { ThemeContextBundle } from '../context-registry'\n${wrapperImports}\n${stylesImports}\n${authImports}\n${faviconImports}\n\nexport const THEME_CONTEXT_REGISTRY_GENERATED: Record<string, ThemeContextBundle> = {\n${mappings}\n}\n`
}

function buildManifestPayload(themes, defaultThemeId) {
  return {
    version: 1,
    defaultTheme: defaultThemeId,
    themes: themes.map((theme) => {
      const entry = {
        id: theme.id,
        name: theme.name,
        description: theme.description,
        status: theme.status,
      }
      // Persist the operator-controlled disabled flag so the manifest matches
      // each theme.json's intent. Omitted when false to keep the manifest
      // diff-free for themes that have never been disabled.
      if (theme.disabled) entry.disabled = true
      return entry
    }),
  }
}

async function writeIfChanged(targetPath, content) {
  await fs.mkdir(path.dirname(targetPath), { recursive: true })

  let current = ''
  try {
    current = await fs.readFile(targetPath, 'utf8')
  } catch {
    current = ''
  }

  if (current === content) {
    return false
  }

  await fs.writeFile(targetPath, content, 'utf8')
  return true
}

async function main() {
  const { themes, defaultThemeId } = await discoverThemes()

  const shellRegistryPath = path.join(GENERATED_ROOT, 'theme-shell-registry.generated.ts')
  const pageRegistryPath = path.join(GENERATED_ROOT, 'theme-page-registry.generated.ts')
  const contractRegistryPath = path.join(GENERATED_ROOT, 'theme-contract-registry.generated.ts')
  const contextRegistryPath = path.join(GENERATED_ROOT, 'theme-context-registry.generated.ts')

  const shellRegistryChanged = await writeIfChanged(shellRegistryPath, buildShellRegistryFile(themes))
  const pageRegistryChanged = await writeIfChanged(pageRegistryPath, buildPageRegistryFile(themes))
  const contractRegistryChanged = await writeIfChanged(
    contractRegistryPath,
    buildContractRegistryFile(themes)
  )
  const contextRegistryChanged = await writeIfChanged(
    contextRegistryPath,
    buildContextRegistryFile(themes)
  )

  const manifestPayload = buildManifestPayload(themes, defaultThemeId)
  const manifestContent = `${JSON.stringify(manifestPayload, null, 2)}\n`
  const manifestChanged = await writeIfChanged(MANIFEST_PATH, manifestContent)

  const changedFiles = [
    shellRegistryChanged && shellRegistryPath,
    pageRegistryChanged && pageRegistryPath,
    contractRegistryChanged && contractRegistryPath,
    contextRegistryChanged && contextRegistryPath,
    manifestChanged && MANIFEST_PATH,
  ].filter(Boolean)

  if (changedFiles.length === 0) {
    console.log(`Theme contracts synced. ${themes.length} theme(s) discovered. No file changes.`)
    return
  }

  console.log(`Theme contracts synced. ${themes.length} theme(s) discovered.`)
  for (const filePath of changedFiles) {
    console.log(`updated: ${path.relative(PROJECT_ROOT, filePath)}`)
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exit(1)
})
